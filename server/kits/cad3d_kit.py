#!/usr/bin/env python3
"""
cad3d_kit.py — Mesin Pembuat Model CAD 3D Siap Cetak 3D Printer (.stl & .obj)
dan Visualisasi Plot Permukaan 3D Ilmiah / Blueprint Teknik 300-DPI (.png).

Fitur:
  1. Menghasilkan file mesh 3D standar industri `.stl` (ASCII STL) dan `.obj` (Wavefront OBJ)
     untuk komponen mekanik parametrik (seperti Roda Gigi Transmisi / Spur Gear 3D).
  2. Merender Blueprint 3D Dual-Panel 300-DPI (Panel Kiri: Wireframe/Mesh 3D Roda Gigi Mekanik;
     Panel Kanan: 3D Surface Response Plot Optimasi Suhu vs Tekanan vs Kapabilitas Cpk).

Cara pakai:
  python3 kits/cad3d_kit.py output_prefix
"""

import math
import os
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d.art3d import Poly3DCollection
import numpy as np


def generate_spur_gear_triangles(teeth: int = 16, r_inner: float = 18.0, r_Pitch: float = 26.0, r_outer: float = 30.0, thickness: float = 8.0):
    """Bangun daftar segitiga (x, y, z) 3D untuk roda gigi mekanik (Spur Gear) tertutup."""
    n_seg = teeth * 4
    angles = [2.0 * math.pi * i / n_seg for i in range(n_seg)]
    radii = []
    for i in range(n_seg):
        mod = i % 4
        radii.append(r_outer if mod in (1, 2) else r_Pitch)

    z0, z1 = 0.0, float(thickness)
    triangles = []

    for i in range(n_seg):
        ni = (i + 1) % n_seg
        a0, a1 = angles[i], angles[ni]
        ro0, ro1 = radii[i], radii[ni]

        # Titik lingkar dalam (lubang poros) & luar (gigi)
        p_in0_b = (r_inner * math.cos(a0), r_inner * math.sin(a0), z0)
        p_in1_b = (r_inner * math.cos(a1), r_inner * math.sin(a1), z0)
        p_out0_b = (ro0 * math.cos(a0), ro0 * math.sin(a0), z0)
        p_out1_b = (ro1 * math.cos(a1), ro1 * math.sin(a1), z0)

        p_in0_t = (r_inner * math.cos(a0), r_inner * math.sin(a0), z1)
        p_in1_t = (r_inner * math.cos(a1), r_inner * math.sin(a1), z1)
        p_out0_t = (ro0 * math.cos(a0), ro0 * math.sin(a0), z1)
        p_out1_t = (ro1 * math.cos(a1), ro1 * math.sin(a1), z1)

        # Permukaan atas
        triangles.append((p_in0_t, p_out0_t, p_out1_t))
        triangles.append((p_in0_t, p_out1_t, p_in1_t))
        # Permukaan bawah
        triangles.append((p_in0_b, p_out1_b, p_out0_b))
        triangles.append((p_in0_b, p_in1_b, p_out1_b))
        # Dinding gigi luar
        triangles.append((p_out0_b, p_out1_b, p_out1_t))
        triangles.append((p_out0_b, p_out1_t, p_out0_t))
        # Dinding poros dalam
        triangles.append((p_in0_b, p_in1_t, p_in1_b))
        triangles.append((p_in0_b, p_in0_t, p_in1_t))

    return triangles


def export_stl_and_obj(triangles, stl_path: str, obj_path: str) -> dict:
    os.makedirs(os.path.dirname(os.path.abspath(stl_path)), exist_ok=True)
    with open(stl_path, "w", encoding="utf-8") as sf:
        sf.write("solid SpurGear3D\n")
        for t in triangles:
            sf.write("  facet normal 0.0 0.0 1.0\n    outer loop\n")
            for vx, vy, vz in t:
                sf.write(f"      vertex {vx:.4f} {vy:.4f} {vz:.4f}\n")
            sf.write("    endloop\n  endfacet\n")
        sf.write("endsolid SpurGear3D\n")

    # Export Wavefront .obj
    vert_map = {}
    verts = []
    faces = []
    for t in triangles:
        f_idx = []
        for v in t:
            key = (round(v[0], 4), round(v[1], 4), round(v[2], 4))
            if key not in vert_map:
                vert_map[key] = len(verts) + 1
                verts.append(key)
            f_idx.append(vert_map[key])
        faces.append(f_idx)

    with open(obj_path, "w", encoding="utf-8") as of:
        of.write("# SpurGear3D Wavefront OBJ — Generated by cad3d_kit.py\n")
        for vx, vy, vz in verts:
            of.write(f"v {vx:.4f} {vy:.4f} {vz:.4f}\n")
        for f1, f2, f3 in faces:
            of.write(f"f {f1} {f2} {f3}\n")

    return {"stl_path": stl_path, "obj_path": obj_path, "triangles": len(triangles), "vertices": len(verts)}


def render_3d_blueprint_png(triangles, out_png: str) -> str:
    fig = plt.figure(figsize=(11.5, 5.2), dpi=300)
    fig.patch.set_facecolor("#FFFFFF")

    # Panel 1: 3D CAD Spur Gear Mesh
    ax1 = fig.add_subplot(1, 2, 1, projection="3d")
    poly = Poly3DCollection(triangles, alpha=0.88, facecolor="#38BDF8", edgecolor="#1E3A8A", linewidths=0.35)
    ax1.add_collection3d(poly)
    ax1.set_xlim(-35, 35)
    ax1.set_ylim(-35, 35)
    ax1.set_zlim(-5, 14)
    ax1.view_init(elev=32, azim=-45)
    ax1.set_title("Model CAD 3D Parametrik: Roda Gigi Transmisi (16 Gigi)", fontsize=11, fontweight="bold", color="#1F3A5F", pad=12)
    ax1.set_xlabel("X (mm)")
    ax1.set_ylabel("Y (mm)")
    ax1.set_zlabel("Z (mm)")

    # Panel 2: 3D Response Surface Plot (Suhu x Kecepatan -> Cpk)
    ax2 = fig.add_subplot(1, 2, 2, projection="3d")
    x = np.linspace(165, 195, 36)
    y = np.linspace(800, 1600, 36)
    X, Y = np.meshgrid(x, y)
    Z = 1.65 - 0.0018 * ((X - 180.0) ** 2) - 0.0000015 * ((Y - 1250.0) ** 2)
    surf = ax2.plot_surface(X, Y, Z, cmap="viridis", edgecolor="none", alpha=0.92)
    ax2.view_init(elev=28, azim=-125)
    ax2.set_title("Kurva Permukaan Respons 3D: Suhu × RPM vs Indeks Cpk", fontsize=11, fontweight="bold", color="#1F3A5F", pad=12)
    ax2.set_xlabel("Suhu (°C)")
    ax2.set_ylabel("Kecepatan (RPM)")
    ax2.set_zlabel("Indeks Cpk")
    fig.colorbar(surf, ax=ax2, shrink=0.65, pad=0.08)

    plt.tight_layout()
    os.makedirs(os.path.dirname(os.path.abspath(out_png)), exist_ok=True)
    fig.savefig(out_png, dpi=300, bbox_inches="tight")
    plt.close(fig)
    return out_png


if __name__ == "__main__":
    prefix = sys.argv[1] if len(sys.argv) > 1 else "cad_3d_sample"
    tris = generate_spur_gear_triangles()
    info = export_stl_and_obj(tris, prefix + ".stl", prefix + ".obj")
    png_p = render_3d_blueprint_png(tris, prefix + "_blueprint.png")
    print(f"OK -> STL: {info['stl_path']} | OBJ: {info['obj_path']} | PNG: {png_p} ({info['triangles']} triangles)")
